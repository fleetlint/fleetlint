// Package docs generates the reference pages that must never drift from the
// code: one page per rule from the presets, and the CEL reference from the
// environment. `fleetlint docs --check` fails when the pages in the output
// directory differ; the documentation repository runs it.
package docs

import (
	"bytes"
	"fmt"
	"slices"
	"sort"
	"strings"

	"github.com/fleetlint/fleetlint/internal/artifacts"
	"github.com/fleetlint/fleetlint/internal/catalog"
	"github.com/fleetlint/fleetlint/internal/celenv"
	"github.com/fleetlint/fleetlint/internal/model"
	"github.com/fleetlint/fleetlint/internal/stacks"
)

// Page is a generated file, path relative to the docs directory.
type Page struct {
	Path    string
	Content []byte
}

// Options adapt the generated pages to where they are published.
type Options struct {
	// IndexFile names the rule index inside rules/ (README.md for a plain
	// directory, _index.md for a Hugo section).
	IndexFile string
}

// Generate renders every generated page. Each page ends with the catalog
// version it describes, because rules are versioned apart from the tool.
func Generate(opts Options) ([]Page, error) {
	if opts.IndexFile == "" {
		opts.IndexFile = "README.md"
	}
	rules, byPreset, err := loadPresets()
	if err != nil {
		return nil, err
	}
	defs, err := catalog.Builtin().StackDefs()
	if err != nil {
		return nil, err
	}
	arts, err := catalog.Builtin().ArtifactDefs()
	if err != nil {
		return nil, err
	}
	pages := []Page{
		{Path: "rules/" + opts.IndexFile, Content: rulesIndex(rules, byPreset)},
		{Path: "rules/capabilities.md", Content: capabilityMatrix(rules, defs, arts)},
		{Path: "cel-reference.md", Content: celReference()},
	}
	for _, r := range rules {
		pages = append(pages, Page{Path: "rules/" + pageName(r.ID) + ".md", Content: rulePage(r)})
	}
	footer := []byte("\n---\n\nGenerated by `fleetlint docs` from catalog " + catalog.ModuleVersion() + ".\n")
	for i := range pages {
		pages[i].Content = append(bytes.TrimRight(pages[i].Content, "\n"), append([]byte("\n"), footer...)...)
	}
	return pages, nil
}

// prose makes catalog text safe as Markdown prose: outside code spans, an
// angle bracket is text (`<digest>`, `<name>`), not the start of an HTML tag
// that a renderer would drop.
func prose(text string) string {
	parts := strings.Split(text, "`")
	for i := 0; i < len(parts); i += 2 {
		parts[i] = strings.NewReplacer("<", "&lt;", ">", "&gt;").Replace(parts[i])
	}
	return strings.Join(parts, "`")
}

// refLinks writes URLs so that Markdown renders them as links.
// refLinks renders the sources as Markdown list items: the link, then
// the kind and the section where the rule states them.
func refLinks(refs []model.Ref) []string {
	links := make([]string, 0, len(refs))
	for _, ref := range refs {
		link := ref.URL
		if strings.HasPrefix(link, "https://") {
			link = "[" + link + "](" + link + ")"
		}
		var extra []string
		if ref.Kind != "" {
			extra = append(extra, ref.Kind)
		}
		if ref.Section != "" {
			extra = append(extra, ref.Section)
		}
		if len(extra) > 0 {
			link += " (" + strings.Join(extra, ", ") + ")"
		}
		links = append(links, "- "+link)
	}
	return links
}

func loadPresets() ([]model.Rule, map[string][]string, error) {
	seen := map[string]model.Rule{}
	byPreset := map[string][]string{}
	for _, name := range catalog.Presets() {
		cats, err := catalog.Loader{}.Load("fleetlint:" + name)
		if err != nil {
			return nil, nil, err
		}
		own := cats[len(cats)-1]
		for _, r := range own.Rules {
			seen[r.ID] = r
			byPreset[name] = append(byPreset[name], r.ID)
		}
	}
	rules := make([]model.Rule, 0, len(seen))
	for _, r := range seen {
		rules = append(rules, r)
	}
	sort.Slice(rules, func(i, j int) bool { return rules[i].ID < rules[j].ID })
	return rules, byPreset, nil
}

func rulesIndex(rules []model.Rule, byPreset map[string][]string) []byte {
	var b bytes.Buffer
	b.WriteString("# Rule reference\n\nGenerated by `fleetlint docs`; do not edit. One page per rule shipped in the presets.\n\n")
	b.WriteString("| Rule | Severity | Tiers | Stacks | Scope | Preset |\n|---|---|---|---|---|---|\n")
	presetOf := map[string]string{}
	for p, ids := range byPreset {
		for _, id := range ids {
			presetOf[id] = p
		}
	}
	for _, r := range rules {
		fmt.Fprintf(&b, "| [%s](%s.md) | %s | %s | %s | %s | %s |\n",
			r.ID, pageName(r.ID), r.Severity, tiers(r), stackList(r), scope(r), presetOf[r.ID])
	}
	return b.Bytes()
}

// writeOriginRows adds the rows that depend on how the rule was taken in.
func writeOriginRows(b *bytes.Buffer, r model.Rule) {
	if r.SelectedBy != "" {
		fmt.Fprintf(b, "| Selected by | %s |\n", r.SelectedBy)
	}
	if r.Locked || r.MinSeverity != "" || !r.ExceptionsAllowed() {
		fmt.Fprintf(b, "| Policy | locked: %t, floor: %s, exceptions: %t |\n", r.Locked, r.Floor(), r.ExceptionsAllowed())
	}
}

func pageName(id string) string { return strings.ReplaceAll(id, "/", "--") }

// combineOf is a capability's combine, `all` when it does not say.
func combineOf(r model.Rule) model.Combine {
	if r.Combine == "" {
		return model.CombineAll
	}
	return r.Combine
}

// matrixCell links a stack's implementation; one that declares the
// capability does not apply to the stack (`when: "false"`) reads n/a.
func matrixCell(byID map[string]model.Rule, capRule model.Rule, stack string) string {
	if !slices.Contains(capRule.Implementations, stack) {
		return "-"
	}
	id := capRule.ID + "/" + stack
	if byID[id].When == "false" {
		return fmt.Sprintf("[n/a](%s.md)", pageName(id))
	}
	return fmt.Sprintf("[yes](%s.md)", pageName(id))
}

// capabilityMatrix shows which stack (or artifact kind) implements which
// capability: the catalog's coverage at a glance, and where an
// implementation is missing.
func capabilityMatrix(rules []model.Rule, defs []stacks.Def, arts []artifacts.Def) []byte {
	var b bytes.Buffer
	b.WriteString("# Capabilities\n\nGenerated by `fleetlint docs`; do not edit. A capability states a requirement; each stack implements it with its own tools (`rules/<family>/<name>/<stack>.yaml`). `any` is the stack-neutral implementation: it checks stacks without their own and repositories where no stack is detected, and its satisfiers count for every stack. *Combine* says how the implementations add up: `all`, every implementation that runs must pass; `any`, one passing is enough (for what belongs to the repository rather than to each stack). `n/a` means the requirement does not apply to the stack (its page says why). A dash means no implementation yet; a report says so for a repository with that stack.\n\n")
	byID := map[string]model.Rule{}
	for _, r := range rules {
		byID[r.ID] = r
	}
	b.WriteString("| Capability | Combine |")
	for _, d := range defs {
		fmt.Fprintf(&b, " %s |", d.ID)
	}
	b.WriteString(" any |\n|---|")
	b.WriteString(strings.Repeat("---|", len(defs)+2) + "\n")
	for _, r := range rules {
		if r.Kind != model.KindCapability || r.By == model.ByArtifact {
			continue
		}
		fmt.Fprintf(&b, "| [%s](%s.md) | %s |", r.ID, pageName(r.ID), combineOf(r))
		for _, id := range append(stacks.IDs(defs), stacks.Any) {
			fmt.Fprintf(&b, " %s |", matrixCell(byID, r, id))
		}
		b.WriteString("\n")
	}
	b.WriteString("\n## Stacks\n\n| Stack | Detected by |\n|---|---|\n")
	for _, d := range defs {
		markers := make([]string, 0, len(d.Detect))
		for _, m := range d.Detect {
			markers = append(markers, "`"+m.File+m.Glob+"`")
		}
		fmt.Fprintf(&b, "| %s (`%s`) | %s |\n", d.Title, d.ID, strings.Join(markers, ", "))
	}
	writeArtifactMatrix(&b, rules, byID, arts)
	return b.Bytes()
}

// writeArtifactMatrix is the matrix for capabilities keyed by published
// artifact (`by: artifact`): one column per artifact kind the catalog
// defines, and the kinds themselves with how each is detected.
func writeArtifactMatrix(b *bytes.Buffer, rules []model.Rule, byID map[string]model.Rule, arts []artifacts.Def) {
	if len(arts) == 0 {
		return
	}
	b.WriteString("\n## Artifacts\n\nA capability keyed by artifact (`by: artifact`) is checked once per published artifact, with an implementation per kind (`rules/<family>/<name>/<artifact>.yaml`): a repository that publishes binaries and an npm package must satisfy both, two images are checked one by one, and the report names the one that does not. There is no `any` implementation here: what counts as signed, attested or described differs per kind. `n/a` means the requirement does not apply to the kind (its page says why). Artifacts are detected from the workflows that publish them, by the catalog's `artifacts/<kind>.yaml`, which names the instances of a kind where it can (an image reference, a chart path); a repository pins `facts: {artifacts: [...]}` when detection misses one.\n\n")
	b.WriteString("| Capability |")
	for _, d := range arts {
		fmt.Fprintf(b, " %s |", d.ID)
	}
	b.WriteString("\n|---|" + strings.Repeat("---|", len(arts)) + "\n")
	for _, r := range rules {
		if r.Kind != model.KindCapability || r.By != model.ByArtifact {
			continue
		}
		fmt.Fprintf(b, "| [%s](%s.md) |", r.ID, pageName(r.ID))
		for _, d := range arts {
			fmt.Fprintf(b, " %s |", matrixCell(byID, r, d.ID))
		}
		b.WriteString("\n")
	}
	b.WriteString("\n| Artifact | What it is | Detected from |\n|---|---|---|\n")
	for _, d := range arts {
		fmt.Fprintf(b, "| `%s` | %s | %s |\n", d.ID, d.Title, strings.ReplaceAll(d.Summary, "|", "\\|"))
	}
}

// writeCapabilityNote links a capability to its implementations and an
// implementation to its capability.
func writeCapabilityNote(b *bytes.Buffer, r model.Rule) {
	switch {
	case r.Kind == model.KindCapability:
		links := make([]string, 0, len(r.Implementations))
		for _, s := range r.Implementations {
			links = append(links, fmt.Sprintf("[%s](%s.md)", s, pageName(r.ID+"/"+s)))
		}
		if r.By == model.ByArtifact {
			fmt.Fprintf(b, "A capability keyed by published artifact: each kind the release publishes is checked by its own implementation, and every one must pass. Implemented for %s.\n\n", strings.Join(links, ", "))
			return
		}
		fmt.Fprintf(b, "A capability: each stack checks it with its own tools. Implemented for %s.\n\n", strings.Join(links, ", "))
		if combineOf(r) == model.CombineAny {
			b.WriteString("Combine: `any`. One implementation passing is enough: this belongs to the repository, not to each stack, so the stack that does it decides and the others pass with it.\n\n")
		} else {
			b.WriteString("Combine: `all`. Every implementation that runs must pass: each stack in the repository meets the requirement with its own tools.\n\n")
		}
	case r.Stack == stacks.Any:
		fmt.Fprintf(b, "The stack-neutral implementation of [%s](%s.md): it checks stacks without an implementation of their own and repositories where no stack is detected, and its satisfiers count for every stack.\n\n", r.Capability, pageName(r.Capability))
	case r.Artifact != "":
		fmt.Fprintf(b, "Implements [%s](%s.md) for the `%s` artifact: it runs when the release publishes one (see [artifacts](capabilities.md#artifacts)).\n\n", r.Capability, pageName(r.Capability), r.Artifact)
	case r.Capability != "":
		fmt.Fprintf(b, "Implements [%s](%s.md) for %s.\n\n", r.Capability, pageName(r.Capability), r.Stack)
	}
}

func rulePage(r model.Rule) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "# %s\n\n%s\n\n", r.ID, prose(r.Title))
	writeCapabilityNote(&b, r)
	fmt.Fprintf(&b, "| | |\n|---|---|\n| Severity | %s |\n| Tiers | %s |\n| %s | %s |\n| Scope | %s |\n| Kind | %s |\n| Source | %s |\n",
		r.Severity, tiers(r), targetKey(r), targetList(r), scope(r), r.Kind, r.Source)
	writeOriginRows(&b, r)
	b.WriteString("\n")
	fmt.Fprintf(&b, "## Requirement\n\n%s\n\n", prose(strings.TrimSpace(r.Requirement)))
	if r.Rationale != "" {
		fmt.Fprintf(&b, "## Why\n\n%s\n\n", prose(strings.TrimSpace(r.Rationale)))
	}
	if r.Gate != "" && r.Kind != model.KindCapability {
		fmt.Fprintf(&b, "## Capability applies when\n\n```cel\n%s\n```\n\n", strings.TrimSpace(r.Gate))
	}
	if r.When != "" {
		fmt.Fprintf(&b, "## Applies when\n\n```cel\n%s\n```\n\n", strings.TrimSpace(r.When))
	}
	if r.Expr != "" {
		b.WriteString("## Check\n\n")
		if r.Foreach != "" {
			fmt.Fprintf(&b, "For each `item` in:\n\n```cel\n%s\n```\n\n", strings.TrimSpace(r.Foreach))
		}
		fmt.Fprintf(&b, "```cel\n%s\n```\n\n", strings.TrimSpace(r.Expr))
	}
	if len(r.Params) > 0 {
		b.WriteString("## Parameters\n\n")
		keys := make([]string, 0, len(r.Params))
		for k := range r.Params {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			fmt.Fprintf(&b, "- `%s`: `%v`\n", k, r.Params[k])
		}
		b.WriteString("\n")
	}
	fmt.Fprintf(&b, "## Fix\n\n%s\n\n", prose(r.Fix.Human))
	if r.Fix.Agent != "" {
		fmt.Fprintf(&b, "Agent instruction: %s\n\n", prose(r.Fix.Agent))
	}
	if len(r.Fix.Actions) > 0 {
		fmt.Fprintf(&b, "`fleetlint fix` can apply this rule's fix automatically (%d action(s)).\n\n", len(r.Fix.Actions))
	}
	if len(r.Refs) > 0 {
		if r.Locate != "" {
			fmt.Fprintf(&b, "A finding of this rule points at `%s`.\n\n", r.Locate)
		}
		fmt.Fprintf(&b, "## Sources\n\n%s\n", strings.Join(refLinks(r.Refs), "\n"))
	}
	// Exactly one trailing newline, whichever section came last.
	return append(bytes.TrimRight(b.Bytes(), "\n"), '\n')
}

func celReference() []byte {
	var b bytes.Buffer
	b.WriteString("# CEL reference\n\nGenerated by `fleetlint docs`; do not edit. Everything an `expr` rule can use.\n\n## Variables\n\n| Variable | Contents |\n|---|---|\n")
	for _, v := range celenv.Variables {
		fmt.Fprintf(&b, "| `%s` | %s |\n", v.Signature, v.Doc)
	}
	b.WriteString("\n## Functions\n\n| Function | Returns |\n|---|---|\n")
	for _, a := range celenv.Accessors {
		fmt.Fprintf(&b, "| `%s` | %s |\n", a.Signature, a.Doc)
	}
	b.WriteString("\nStandard CEL operators, macros (`all`, `exists`, `filter`, `map`, `has`) and string functions (`contains`, `startsWith`, `endsWith`, `matches`, `size`) are available. A rule's result must be a bool; with `foreach`, the list expression is evaluated first and `expr` once per `item`.\n")
	return b.Bytes()
}

func tiers(r model.Rule) string {
	if len(r.Tiers) == 0 {
		return "all"
	}
	parts := make([]string, 0, len(r.Tiers))
	for _, t := range r.Tiers {
		parts = append(parts, fmt.Sprint(t))
	}
	return strings.Join(parts, ", ")
}

func stackList(r model.Rule) string {
	if len(r.Stacks) == 0 {
		return "any"
	}
	return strings.Join(r.Stacks, ", ")
}

// targetKey and targetList are the row that says where an implementation
// runs: its artifact kind, or the rule's stacks.
func targetKey(r model.Rule) string {
	if r.Artifact != "" {
		return "Artifact"
	}
	return "Stacks"
}

func targetList(r model.Rule) string {
	if r.Artifact != "" {
		return r.Artifact
	}
	return stackList(r)
}

func scope(r model.Rule) string {
	if r.Scope == "" {
		return string(model.ScopeEach)
	}
	return string(r.Scope)
}
