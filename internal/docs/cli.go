package docs

import (
	"bytes"
	"fmt"
	"regexp"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
)

// CLI is what cli-reference.md documents: the command tree, the exit
// codes and the environment variables.
type CLI struct {
	Root        *cobra.Command
	ExitCodes   []ExitCode
	Environment []EnvVar
}

// ExitCode is a row of the exit-code table; Meaning is Markdown.
type ExitCode struct {
	Code    int
	Meaning string
}

// EnvVar is a row of the environment table: variables read for one
// purpose, described in Markdown.
type EnvVar struct {
	Names []string
	Doc   string
	// InstallOnly marks variables the install script reads, not fleetlint.
	InstallOnly bool
}

// DefaultAnnotation on a flag gives its default in words, for a default
// that depends on where the command runs.
const DefaultAnnotation = "fleetlint-docs-default"

// completionCmd is cobra's completion command, documented in one section.
const completionCmd = "completion"

func cliReference(c CLI) []byte {
	var b bytes.Buffer
	root := c.Root
	fmt.Fprintf(&b, "# CLI reference\n\nGenerated by `fleetlint docs`; do not edit. Every command and flag of `%s`, its exit codes and the environment variables it reads.\n\n", root.Name())
	b.WriteString("## Global flags\n\nEvery command takes these.\n\n")
	writeFlags(&b, root.PersistentFlags(), [][2]string{{"-h, --help", "help for the command"}})
	b.WriteString("\n## Commands\n\n")
	writeCommand(&b, root, root.LocalNonPersistentFlags())
	for _, cmd := range subcommands(root) {
		if cmd.Name() == completionCmd && cmd.Parent() == root {
			writeCompletion(&b, cmd)
			continue
		}
		writeCommand(&b, cmd, cmd.LocalFlags())
	}
	b.WriteString("## Exit codes\n\n| Code | Meaning |\n|---|---|\n")
	for _, e := range c.ExitCodes {
		fmt.Fprintf(&b, "| `%d` | %s |\n", e.Code, cell(e.Meaning))
	}
	b.WriteString("\n## Environment variables\n\n| Variable | Effect |\n|---|---|\n")
	for _, v := range c.Environment {
		names := make([]string, len(v.Names))
		for i, n := range v.Names {
			names[i] = "`" + n + "`"
		}
		doc := v.Doc
		if v.InstallOnly {
			doc = "Read by the install script, not by `" + root.Name() + "`: " + doc
		}
		fmt.Fprintf(&b, "| %s | %s |\n", strings.Join(names, ", "), cell(doc))
	}
	return b.Bytes()
}

// subcommands are the documented commands below cmd, depth first in
// cobra's order; help and hidden commands are left out.
func subcommands(cmd *cobra.Command) []*cobra.Command {
	var out []*cobra.Command
	for _, c := range cmd.Commands() {
		if !c.IsAvailableCommand() {
			continue
		}
		out = append(out, c)
		if c.Name() != completionCmd {
			out = append(out, subcommands(c)...)
		}
	}
	return out
}

func writeCommand(b *bytes.Buffer, cmd *cobra.Command, flags *pflag.FlagSet) {
	use := cmd.UseLine()
	if !cmd.Runnable() {
		use = cmd.CommandPath() + " [command]"
	}
	fmt.Fprintf(b, "### %s\n\n%s\n\n```text\n%s\n```\n\n", cmd.CommandPath(), sentence(plain(cmd.Short)), use)
	for _, p := range paragraphs(cmd.Long) {
		fmt.Fprintf(b, "%s\n\n", plain(p))
	}
	if flags.HasAvailableFlags() {
		writeFlags(b, flags, nil)
		b.WriteString("\n")
	}
}

// writeCompletion documents cobra's completion command: one command per
// shell, which differ only in the shell.
func writeCompletion(b *bytes.Buffer, cmd *cobra.Command) {
	shells := subcommands(cmd)
	names := make([]string, len(shells))
	for i, s := range shells {
		names[i] = s.Name()
	}
	fmt.Fprintf(b, "### %s\n\n%s\n\n```text\n%s %s\n```\n\n`%s <shell> --help` says how to load the script.\n\n",
		cmd.CommandPath(), sentence(plain(cmd.Short)), cmd.CommandPath(), strings.Join(names, "|"), cmd.CommandPath())
	if len(shells) > 0 && shells[0].LocalFlags().HasAvailableFlags() {
		writeFlags(b, shells[0].LocalFlags(), nil)
		b.WriteString("\n")
	}
}

// writeFlags is a table of the visible flags, plus extra rows of name and
// description.
func writeFlags(b *bytes.Buffer, flags *pflag.FlagSet, extra [][2]string) {
	b.WriteString("| Flag | Default | Description |\n|---|---|---|\n")
	flags.VisitAll(func(f *pflag.Flag) {
		if f.Hidden {
			return
		}
		name, usage := pflag.UnquoteUsage(f)
		spell := "--" + f.Name
		if f.Shorthand != "" {
			spell = "-" + f.Shorthand + ", " + spell
		}
		if name != "" {
			spell += " " + name
		}
		fmt.Fprintf(b, "| `%s` | %s | %s |\n", spell, flagDefault(f), cell(plain(usage)))
	})
	for _, row := range extra {
		fmt.Fprintf(b, "| `%s` |  | %s |\n", row[0], cell(plain(row[1])))
	}
}

// flagDefault is the default shown for a flag; a zero value shows nothing.
func flagDefault(f *pflag.Flag) string {
	if words, ok := f.Annotations[DefaultAnnotation]; ok {
		return cell(strings.Join(words, " "))
	}
	switch f.DefValue {
	case "", "false", "0", "[]":
		return ""
	}
	return "`" + f.DefValue + "`"
}

// paragraphs splits help text at blank lines and joins each paragraph's
// lines, so a line break never starts a Markdown block.
func paragraphs(text string) []string {
	var out []string
	for _, p := range strings.Split(strings.TrimSpace(text), "\n\n") {
		if p = strings.Join(strings.Fields(p), " "); p != "" {
			out = append(out, p)
		}
	}
	return out
}

// helpCode are the words of help text set as code: flags, runs of flags
// and environment variables. As text, a typographer would turn `--` into
// a dash.
var helpCode = regexp.MustCompile(`--?[a-zA-Z][a-z0-9-]*(?: --?[a-zA-Z][a-z0-9-]*)*|\$?[A-Z][A-Z0-9]*(?:_[A-Z0-9]+)+`)

// plain makes help text, which is not Markdown, safe as Markdown: flags
// and variables become code, and the characters that would start
// emphasis, a tag or an escape are escaped.
func plain(text string) string {
	var b strings.Builder
	last := 0
	for _, m := range helpCode.FindAllStringIndex(text, -1) {
		if m[0] > 0 && !strings.ContainsRune(" (\"'[/", rune(text[m[0]-1])) {
			continue // inside a word: per-repo, auto-detection
		}
		b.WriteString(escapeHelp(text[last:m[0]]))
		b.WriteString("`" + text[m[0]:m[1]] + "`")
		last = m[1]
	}
	b.WriteString(escapeHelp(text[last:]))
	return b.String()
}

func escapeHelp(text string) string {
	return strings.NewReplacer(`\`, `\\`, "*", `\*`, "_", `\_`, "`", "\\`", "<", "&lt;", ">", "&gt;").Replace(text)
}

// cell keeps text inside a table cell.
func cell(text string) string { return strings.ReplaceAll(text, "|", `\|`) }

// sentence ends help text with a full stop.
func sentence(text string) string {
	if text == "" || strings.ContainsAny(text[len(text)-1:], ".!?:") {
		return text
	}
	return text + "."
}
