package docs

import (
	"bytes"
	"errors"
	"io/fs"
	"path"
	"slices"
	"strings"
)

// footerPrefix starts the last line of every generated page; it tells a
// generated page from a written one.
const footerPrefix = "Generated by `fleetlint docs` from catalog "

// IsGenerated reports whether a page was written by `fleetlint docs`.
func IsGenerated(content []byte) bool {
	body := bytes.TrimRight(content, "\n")
	last := body[bytes.LastIndexByte(body, '\n')+1:]
	return bytes.HasPrefix(last, []byte(footerPrefix))
}

// Orphans are the generated pages in the directories pages are written to
// that are no longer generated, such as the page of a removed rule. Pages
// written by hand and other directories are left alone.
func Orphans(fsys fs.FS, pages []Page) ([]string, error) {
	current := map[string]bool{}
	var dirs []string
	for _, p := range pages {
		current[p.Path] = true
		if d := path.Dir(p.Path); !slices.Contains(dirs, d) {
			dirs = append(dirs, d)
		}
	}
	var orphans []string
	for _, dir := range dirs {
		found, err := orphansIn(fsys, dir, current)
		if err != nil {
			return nil, err
		}
		orphans = append(orphans, found...)
	}
	slices.Sort(orphans)
	return orphans, nil
}

// orphansIn are the generated pages of one directory that are not current.
func orphansIn(fsys fs.FS, dir string, current map[string]bool) ([]string, error) {
	entries, err := fs.ReadDir(fsys, dir)
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var orphans []string
	for _, e := range entries {
		name := path.Join(dir, e.Name())
		if !e.Type().IsRegular() || !strings.HasSuffix(name, ".md") || current[name] {
			continue
		}
		content, err := fs.ReadFile(fsys, name)
		if err != nil {
			return nil, err
		}
		if IsGenerated(content) {
			orphans = append(orphans, name)
		}
	}
	return orphans, nil
}
